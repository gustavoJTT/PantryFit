CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE pantry_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255) NOT NULL,
    unit VARCHAR(20) NOT NULL CHECK (unit IN ('GRAM', 'MILLILITER', 'UNIT')),
    quantity NUMERIC(12, 3) NOT NULL CHECK (quantity >= 0),
    minimum_quantity NUMERIC(12, 3) NOT NULL CHECK (minimum_quantity >= 0),
    calories_per_100g NUMERIC(10, 2),
    proteins_per_100g NUMERIC(10, 2),
    carbohydrates_per_100g NUMERIC(10, 2),
    fats_per_100g NUMERIC(10, 2),
    fibers_per_100g NUMERIC(10, 2)
);

CREATE INDEX idx_pantry_items_user_id ON pantry_items(user_id);
CREATE INDEX idx_pantry_items_category ON pantry_items(category);

CREATE TABLE meals (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    name VARCHAR(255) NOT NULL,
    time TIME NOT NULL,
    period VARCHAR(255) NOT NULL,
    calories NUMERIC(10, 2) NOT NULL,
    proteins NUMERIC(10, 2) NOT NULL,
    carbohydrates NUMERIC(10, 2) NOT NULL,
    fats NUMERIC(10, 2) NOT NULL,
    fibers NUMERIC(10, 2) NOT NULL,
    icon_code_point INTEGER
);

CREATE INDEX idx_meals_user_id ON meals(user_id);

CREATE TABLE meal_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id UUID NOT NULL REFERENCES meals(id) ON DELETE CASCADE,
    pantry_item_id BIGINT REFERENCES pantry_items(id),
    name VARCHAR(255) NOT NULL,
    is_from_pantry BOOLEAN NOT NULL,
    calories NUMERIC(10, 2) NOT NULL,
    proteins NUMERIC(10, 2) NOT NULL,
    carbohydrates NUMERIC(10, 2) NOT NULL,
    fats NUMERIC(10, 2) NOT NULL,
    fibers NUMERIC(10, 2) NOT NULL,
    quantity_g NUMERIC(10, 2) NOT NULL CHECK (quantity_g > 0)
);

CREATE INDEX idx_meal_items_meal_id ON meal_items(meal_id);
CREATE INDEX idx_meal_items_pantry_item_id ON meal_items(pantry_item_id);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pantry_item_id BIGINT NOT NULL REFERENCES pantry_items(id),
    meal_id UUID REFERENCES meals(id),
    type VARCHAR(30) NOT NULL CHECK (
        type IN ('ENTRY', 'WITHDRAWAL', 'ADJUSTMENT', 'MEAL_CONSUMPTION')
    ),
    quantity NUMERIC(12, 3) NOT NULL CHECK (quantity > 0),
    reason VARCHAR(255),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_stock_movements_pantry_item_id
    ON stock_movements(pantry_item_id);
CREATE INDEX idx_stock_movements_occurred_at
    ON stock_movements(occurred_at);
CREATE INDEX idx_stock_movements_meal_id
    ON stock_movements(meal_id);
